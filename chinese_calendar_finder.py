# ---------------------------------------------------------------------------
# Небо: юлианские дни и «животное дня» (автономная арифметика, без зависимостей)
# ---------------------------------------------------------------------------
def jdn(d: datetime.date) -> int:
    """Юлианский день для полуночной даты григорианского календаря."""
    a = (14 - d.month) // 12
    y = d.year + 4800 - a
    m = d.month + 12 * a - 3
    return (d.day + (153 * m + 2) // 5 + 365 * y
            + y // 4 - y // 100 + y // 400 - 32045)


def day_branch(d: datetime.date) -> int:
    """Индекс земной ветви дня (0=Крыса ... 11=Кабан) — непрерывный 12-цикл."""
    return (jdn(d) + 5) % 12


# ---------------------------------------------------------------------------
# Месяц по цзеци (через sxtwl)
# ---------------------------------------------------------------------------
def month_info_sxtwl(d: datetime.date):
    """Возвращает (индекс ветви месяца, описание границы месяца) для даты d."""
    if sxtwl is None:
        raise RuntimeError("sxtwl не установлен")
    day = sxtwl.fromSolar(d.year, d.month, d.day)
    mgz = day.getMonthGZ()
    # Проверено на реальных границах цзеци: dz в getMonthGZ использует ту же
    # нумерацию ветвей, что и ZHI_CN / ANIMALS_RU (0=子 Крыса, 2=寅 Тигр, ...).
    br = mgz.dz % 12
    # Найдём начало текущего цзеци-месяца: идём назад, пока метка месяца не изменится.
    start = d
    for _ in range(45):
        prev = start - datetime.timedelta(days=1)
        pd = sxtwl.fromSolar(prev.year, prev.month, prev.day)
        if pd.getMonthGZ().dz != br:
            break
        start = prev
    # Название цзеци, открывающего месяц (идём от начала месяца назад до дня цзеци)
    jq = ""
    cur = start
    for _ in range(3):
        cd = sxtwl.fromSolar(cur.year, cur.month, cur.day)
        if cd.hasJieQi():
            jq = JIEQI_NAMES.get(cd.getJieQi(), f"цзеци #{cd.getJieQi()}")
            break
        cur = cur - datetime.timedelta(days=1)
    return br, start, jq


# ---------------------------------------------------------------------------
# Поиск дат
# ---------------------------------------------------------------------------
def find_dates(year: int, day_animal: int, month_animal: int):
    """
    Возвращает список найденных дат и сведения о границах месяцев.

    Сканируется полный григорианский год Y (1 января — 31 декабря), а также
    «переходящие» хвосты цзеци-месяцев Крыса/Бык, которые по календарю
    относятся к году Y, но начинаются в декабре Y или январе Y+1
    (окно расширяется: 1 декабря Y-1 ... 28 февраля Y+1).
    """
    scan_start = datetime.date(year - 1, 12, 1)
    scan_end = datetime.date(year + 1, 2, 28)

    results = []
    month_span = {}  # br -> [first_day, last_day] внутри сканируемого окна
    d = scan_start
    one = datetime.timedelta(days=1)
    while d <= scan_end:
        if sxtwl is not None:
            br, mstart, jq = month_info_sxtwl(d)
        else:
            br = approx_month_branch(d)
            mstart, jq = None, ""
        span = month_span.setdefault(br, [d, d])
        span[1] = d
        in_main_year = d.year == year
        # для месяцев Крыса(0)/Бык(1) разрешаем даты из хвоста следующего года,
        # если сам месяц начался в пределах года Y
        tail_ok = (month_animal in (0, 1) and mstart is not None
                   and mstart.year == year)
        if br == month_animal and day_branch(d) == day_animal and (in_main_year or tail_ok):
            results.append((d, mstart, jq))
        d += one
    return results, month_span


def approx_month_branch(d: datetime.date) -> int:
    """
    Резервная (без sxtwl) аппроксимация месяца по средним датам «чжунци»:
    крыса≈21 дек, бык≈20 янв, тигр≈19 фев, кролик≈21 мар, дракон≈20 апр,
    змея≈21 май, лошадь≈21 июн, коза≈23 июл, обезьяна≈23 авг, петух≈23 сен,
    собака≈23 окт, кабан≈22 ноя. Точность ±1 день — используется только если
    sxtwl недоступен.
    """
    anchors = [(12, 21, 0), (1, 20, 1), (2, 19, 2), (3, 21, 3), (4, 20, 4),
               (5, 21, 5), (6, 21, 6), (7, 23, 7), (8, 23, 8), (9, 23, 9),
               (10, 23, 10), (11, 22, 11)]
    cur = datetime.date(d.year, d.month, d.day)
    best = None
    for mm, dd, br in anchors:
        ad = datetime.date(d.year, mm, dd)
        # берём последний якорь <= cur (с учётом перехода через год)
        if ad <= cur:
            key = ad
        else:
            key = datetime.date(d.year - 1, mm, dd)
        if best is None or key > best[0]:
            best = (key, br)
    return best[1]


# ---------------------------------------------------------------------------
# UI: выбор из списка
# ---------------------------------------------------------------------------
def choose_from_list(title: str, options: list, default: int = 0) -> int:
    print(f"\n{title}")
    for i, name in enumerate(options, 1):
        print(f"  {i:2d}) {name}")
    while True:
        raw = input(f"Выберите пункт [1-{len(options)}] (по умолчанию {default+1}): ").strip()
        if raw == "":
            return default
        if raw.isdigit() and 1 <= int(raw) <= len(options):
            return int(raw) - 1
        print("Некорректный ввод, попробуйте ещё раз.")


def ask_year() -> int:
    while True:
        raw = input("\nВведите год по григорианскому календарю (например 3170): ").strip()
        try:
            y = int(raw)
            if 1 <= y <= 9000:
                return y
        except ValueError:
            pass
        print("Год должен быть целым числом от 1 до 9000.")


