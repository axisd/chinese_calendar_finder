#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
chinese_calendar_finder.py
==========================

Поиск конкретной даты (или вариантов дат) по григорианскому календарю
по «китайской» характеристике дня: **день какого животного** в **месяц какого
животного** китайского календаря, например: «день Дракона в Месяц Крысы 3170 года».

Терминология
------------
В китайском календаре каждый день и каждый месяц описывается земными ветвями
(12 «животных»): Крыса, Бык, Тигр, Кролик, Дракон, Змея, Лошадь, Коза, Обезьяна,
Петух, Собака, Кабан.

*   **День** образует непрерывный 12-дневный цикл (не зависит от фаз Луны).
    Поэтому заданный «день недели-животное» повторяется каждые 12 дней —
    в любом месяце их бывает 2–3 штуки.
*   **Месяц** животно́го цикла привязан к солнечным сезонным отрезкам — цзеци
    (節氣/节气). «Месяц Крысы» начинается с зимнего солнцестояния (Дунчжи,
    ≈ 21–22 декабря) и длится до Больших холодов (Дахань, ≈ 20 января), т.е.
    примерно месяц по григорианскому календарю. Границы месяцев НЕ совпадают
    с границами лунных месяцев.
*   **Сезон** китайского календаря (四季): год делится на 4 сезона по 3
    цзеци-месяца; каждый сезон открывается цзе «立» (начало):
      Весна (春): Тигр, Кролик, Дракон (старт — Личунь, ≈4 фев)
      Лето  (夏): Змея, Лошадь, Коза   (старт — Сяли, ≈6 май)
      Осень (秋): Обезьяна, Петух, Собака (старт — Цюли, ≈8 авг)
      Зима  (冬): Кабан, Крыса, Бык    (старт — Дунли, ≈8 ноя)
    Название сезона выводится рядом с названием месяца во всех списках и
    результатах.

Важно про «год»: цзеци-месяцы Крыса и Бык данного григорианского года Y
начинаются в декабре Y и январе Y+1 соответственно. Скрипт сканирует окно
с 1 ноября Y по 20 февраля Y+1, поэтому находит ВСЕ даты «месяц X года Y»,
включая переходящие в следующий год (для месяцев Крыса/Бык это явно
означается примечанием).

Алгоритм
--------
1. По указанному году строится окно дат ~с 1 ноября этого года по 5 февраля
   следующего (этого достаточно, чтобы покрыть все 12 цзеци-месяцев года;
   для месяцев Крыса/Бык показывается реальная дата начала следующего года).
2. Для каждой даты окна вычисляется:
   - животное дня (непрерывный цикл, сверен с библиотекой sxtwl);
   - животное месяца (по цзеци, через sxtwl).
3. Отбираются даты, где день == выбранное животное И месяц == выбранное.
4. Результат верифицируется независимой арифметикой (юлианские дни) для дня.

Зависимости: `pip install sxtwl`  (используется только для точных цзеци;
для дней есть автономная проверка).

Запуск:
    python3 chinese_calendar_finder.py
Скрипт запросит год и предложит выбрать день и месяц из списков.
"""

